package JavaBasics;

//This file contains multiple classes, but only one of them will have the main method that will be executed when we run the program. The other classes can be used for other purposes, such as defining data structures or utility functions.
class anotherMain{
    public static void main(String[] args){
        System.out.println("Hello World from anotherMain");
    }
}
//below is the main method that will be executed when we run the program. We can have multiple classes with main methods, but only one will be executed based on which class we run.
class main {
    public final static void main(String[] args){
        System.out.println("Hello World from main");
    }
    
}


